// Builds src/pages/top-page.generated.ts: the top page HTML with sample images rendered
// from test fixtures, and the favicon. Run via `pnpm build:top-page`.
import { readFileSync, writeFileSync } from 'node:fs';
import { renderPng, type Row } from '../src/render/render.ts';
import { termOf } from '../src/render/text.ts';
import type { ContributionCalendar, Theme } from '../src/types.ts';

const root = new URL('../', import.meta.url);
const calendar = (name: string): ContributionCalendar =>
  JSON.parse(readFileSync(new URL(`test/fixtures/${name}.json`, root), 'utf8')).data.user.contributionsCollection
    .contributionCalendar;

const dataUri = async (rows: Row[], theme: Theme) =>
  `data:image/png;base64,${Buffer.from(await renderPng(rows, theme)).toString('base64')}`;

const year2023 = calendar('year-2023');
const samples: Record<string, string> = {
  SAMPLE_DEFAULT: await dataUri([{ calendar: calendar('default') }], 'light'),
  SAMPLE_TO: await dataUri([{ calendar: year2023, term: termOf(year2023) }], 'light'),
  SAMPLE_PAST_YEARS: await dataUri(
    [2024, 2025, 2026].map((y) => ({ calendar: calendar(`year-${y}`), term: y })),
    'light',
  ),
  SAMPLE_DARK: await dataUri([{ calendar: calendar('default') }], 'dark'),
  SAMPLE_TO_DARK: await dataUri([{ calendar: year2023, term: termOf(year2023) }], 'dark'),
};

const html = readFileSync(new URL('src/pages/top.html', root), 'utf8').replace(/\{\{(\w+)\}\}/g, (_, key: string) => {
  const value = samples[key];
  if (!value) throw new Error(`unknown placeholder: ${key}`);
  return value;
});
const favicon = readFileSync(new URL('assets/favicon.ico', root)).toString('base64');

writeFileSync(
  new URL('src/pages/top-page.generated.ts', root),
  [
    '// Generated by scripts/build-top-page.ts. Do not edit by hand.',
    `export const TOP_PAGE_HTML = ${JSON.stringify(html)};`,
    `export const FAVICON_BASE64 = '${favicon}';`,
    '',
  ].join('\n'),
);
process.stdout.write(`top page: ${html.length} chars, favicon: ${favicon.length} base64 chars\n`);
