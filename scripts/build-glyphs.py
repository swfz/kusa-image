"""Rasterize the glyphs used in the image into per-character alpha masks.

The output is a TypeScript module bundled into the Worker, so text can be drawn
without a font engine at runtime. Noto Mono at 10px matches the default font
("10px monospace") of the CanvasKit-based renderer that kusa-image used before.

Run via `pnpm build:glyphs` (uv + a pinned Pillow version).
"""

import base64
import json
import sys

from PIL import ImageFont

FONT_SIZE = 10
# Sub-pixel x offsets (1 / PHASES px) rendered per glyph.
PHASES = 4
# Every character the image can contain: summary line, month and weekday labels,
# legend and the "YYYY-MM-DD~YYYY-MM-DD" term. Keep in sync with src/render/text.ts.
CHARS = sorted(
    set(
        "0123456789 ()/~-"
        "contributions in the last year max day"
        "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec"
        "Mon Wed Fri Less More"
    )
    - {" "}
)


def main(font_path: str, out_path: str) -> None:
    font = ImageFont.truetype(font_path, FONT_SIZE)
    advance = font.getlength("M")  # monospace: identical for all glyphs

    glyphs: dict[str, list[dict[str, int]]] = {}
    masks = bytearray()
    for ch in CHARS:
        for phase in range(PHASES):
            mask, (x, y) = font.getmask2(ch, mode="L", anchor="ls", start=(phase / PHASES, 0))
            w, h = mask.size
            glyphs.setdefault(ch, []).append({"x": x, "y": y, "w": w, "h": h, "o": len(masks)})
            masks += bytes(mask)

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/build-glyphs.py. Do not edit by hand.\n")
        f.write("export interface Glyph {\n  x: number;\n  y: number;\n  w: number;\n  h: number;\n  o: number;\n}\n")
        f.write(f"export const ADVANCE = {advance};\n")
        f.write(f"export const PHASES = {PHASES};\n")
        f.write(f"export const GLYPHS: Record<string, Glyph[]> = {json.dumps(glyphs, separators=(',', ':'))};\n")
        f.write(f"export const MASKS_BASE64 = '{base64.b64encode(masks).decode()}';\n")

    print(f"chars={len(CHARS)} phases={PHASES} advance={advance} mask_bytes={len(masks)}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
